import assert from "node:assert/strict";
import {personalScenario} from "../src/components/personal.js";
const v = {price:10000,cash:5000,income:500,living:200,debt:50,housing:30,loan:6000,rate:0,years:10,cost:200,reserve:1000};
const r = personalScenario(v);
assert.equal(r.cash, 800);
assert.equal(r.cashGap, -200);
assert.equal(r.monthly, 170);
assert.ok(r.stress2 < r.stress1 && r.stress1 < r.monthly);
assert.equal(personalScenario({...v,income:""}), null);
assert.equal(personalScenario({...v,loan:10001}), null);
assert.equal(personalScenario({...v,years:0}), null);
assert.equal(personalScenario({...v,living:-1}), null);
console.log("ok");
const tiny = personalScenario({...v, rate: 1e-14});
assert.ok(Number.isFinite(tiny.monthly));
assert.ok(Math.abs(tiny.monthly - 170) < 1e-9);
assert.equal(personalScenario({...v, cash: 0, price: 1e308, cost: 1e308}), null);
const delayed = personalScenario({...v, deposit:2000, depositBefore:false, incomeDrop:20});
const returned = personalScenario({...v, deposit:2000, depositBefore:true, incomeDrop:20});
assert.equal(delayed.cash, 800);
assert.equal(returned.cash, 2800);
assert.equal(returned.incomeStress, 70);
assert.equal(personalScenario({...v, incomeDrop:101}), null);
assert.equal(personalScenario({...v, deposit:'', depositBefore:true}), null);
const drop = personalScenario({...v, priceDrop:20});
assert.equal(drop.assessedPrice, 8000);
assert.equal(drop.assessedEquity, 2000);
assert.equal(drop.cash, 800);
assert.equal(drop.monthly, 170);
assert.equal(personalScenario({...v, priceDrop:101}), null);
