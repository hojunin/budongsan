import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const run = (...args) => execFileSync('agent-browser', ['--session','terra-implementation',...args], {encoding:'utf8',timeout:60000}).trim();
const read = (expr) => JSON.parse(JSON.parse(run('eval',`JSON.stringify(${expr})`)));
run('open',`${process.env.CLS_BASE_URL ?? 'http://127.0.0.1:8766'}/compare`);
run('tab','t1'); run('wait','.compare-filters .ts-control');
run('eval',`(()=>{const s=document.querySelector('.compare-filters select');const o=Object.values(s.tomselect.options).find(o=>o.text==='강남구');s.tomselect.setValue(o.value)})()`);
run('wait','1000');
run('eval',`(()=>{const c=[...document.querySelectorAll('input[type=checkbox]')].find(x=>x.closest('label')?.textContent.includes('주소와 단지'));c.click()})()`);
assert.equal(read(`[...document.querySelectorAll('input[type=checkbox]')].find(x=>x.closest('label')?.textContent.includes('주소와 단지')).checked`),true);
run('eval',`(()=>{const s=document.querySelector('.compare-filters select[multiple]').tomselect;s.removeItem(s.items[0])})()`);
run('wait','500');
assert.equal(read(`[...document.querySelectorAll('input[type=checkbox]')].find(x=>x.closest('label')?.textContent.includes('주소와 단지')).checked`),false);
