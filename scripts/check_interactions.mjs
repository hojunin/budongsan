// Requires agent-browser on PATH and npm run dev on port 3000.
import {execFileSync} from "node:child_process";
import assert from "node:assert/strict";
const run = (...args) => execFileSync("agent-browser", args, {encoding: "utf8"}).trim();
const evaluate = (expression) => JSON.parse(JSON.parse(run("eval", `JSON.stringify(${expression})`)));
const wait = (expression) => run("wait", "--fn", expression);
run("set", "viewport", "390", "844");
run("open", "http://localhost:3000/regions");
run("wait", ".tabulator-row");
run("fill", '.table-toolbar input', "노원");
wait('document.querySelectorAll(".tabulator-row").length === 1');
assert.match(evaluate('document.querySelector(".tabulator-row").textContent'), /노원/);
run("click", ".table-toolbar button");
wait('document.querySelectorAll(".tabulator-row").length === 5');
run("click", '.tabulator-col[tabulator-field="last"] .tabulator-col-title');
const sorted = evaluate('[...document.querySelectorAll(".tabulator-cell[tabulator-field=last]")].map(e=>Number(e.textContent.replaceAll(",","")))');
assert.deepEqual(sorted, [...sorted].sort((a, b) => a - b));
run("click", ".tabulator-row:first-child .tabulator-responsive-collapse-toggle");
assert.ok(evaluate('document.querySelector(".tabulator-row .tabulator-responsive-collapse").getBoundingClientRect().height > 0'));
run("fill", '.tabulator-col[tabulator-field="last"] input', "838");
wait('document.querySelectorAll(".tabulator-row").length === 1');
run("click", ".table-toolbar button");
wait('document.querySelectorAll(".tabulator-row").length === 5');
run("eval", '(async()=>{window.testEcharts=await import("/_npm/echarts@6.1.0/dist/echarts.esm.min.js._esm.js")})()');
const chart = 'window.testEcharts.getInstanceByDom(document.querySelector(".interactive-chart"))';
wait(`${chart} != null`);
assert.equal(evaluate(`${chart}.getOption().series.length`), 10);
run("eval", `${chart}.dispatchAction({type:"dataZoom",start:25,end:75})`);
assert.equal(evaluate(`${chart}.getOption().dataZoom[0].start`), 25);
run("eval", `${chart}.dispatchAction({type:"legendToggleSelect",name:${chart}.getOption().series[0].name})`);
assert.equal(evaluate(`${chart}.getOption().legend[0].selected[${chart}.getOption().series[0].name]`), false);
run("eval", 'document.querySelectorAll(".filters form")[1].querySelector("input[value=\\"2\\"]").click()');
wait(`${chart}.getOption().series.length === 15`);
run("check", ".inputs-3a86ea-toggle input");
wait(`${chart}.getOption().yAxis.length === 1`);
const normalized = evaluate(`${chart}.getOption().series[0].data.map(d=>d[1]).filter(d=>d!=null)[0]`);
assert.equal(normalized, 100);
run("fill", ".ts-control input", "강남");
wait('[...document.querySelectorAll(".ts-dropdown .option")].length > 0 && [...document.querySelectorAll(".ts-dropdown .option")].every(e=>e.textContent.includes("강남"))');
run("press", "Enter");
wait(`${chart}.getOption().series.length === 18`);
assert.ok(evaluate('[...document.querySelector(".filters select").selectedOptions].some(e=>e.textContent.includes("강남"))'));
run("eval", 'document.querySelector(".filters select").tomselect.clear()');
wait(`${chart}.getOption().series.length === 0`);
assert.match(evaluate('document.querySelector(".tabulator-placeholder").textContent'), /데이터가 없습니다/);

assert.equal(evaluate('document.querySelectorAll(".observablehq--error").length'), 0);
console.log("PASS table search, numeric sort, column filter, reset, responsive details; chart zoom, legend, multi-indicator, normalized axis");
